// Generates src/data/europeMap.ts — the country shapes Browse's map draws.
//
// Source: Natural Earth 1:50m country borders (public domain), via the
// world-atlas package. Pre-projected to SVG paths once here, so the app
// ships a static file instead of a map library, a tile service or any
// third-party requests.
//
// Not a dependency of the app. To regenerate, from an empty folder:
//   npm install world-atlas@2 topojson-client@3 topojson-simplify@3 d3-geo@3
//   node <path to this file> <path to frontend/src/data/europeMap.ts>
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

// Resolved from the working directory (where the packages were
// installed), not from this file's own location.
const require = createRequire(`${process.cwd()}/`);
const load = (name) => import(pathToFileURL(require.resolve(name)).href);
const { feature } = await load("topojson-client");
const { presimplify, simplify, quantile } = await load("topojson-simplify");
const { geoAzimuthalEqualArea, geoPath } = await load("d3-geo");
const output = process.argv[2];
if (!output) throw new Error("Usage: node build-europe-map.mjs <output .ts file>");

// ISO 3166-1 numeric -> the app's CountryCode, for the 31 EU/EEA + CH
// countries InternEZ covers (data/reference.ts). Every other country in
// view is drawn as grey context.
const COVERED = {
  "040": "AT", "056": "BE", "100": "BG", "191": "HR", "196": "CY", "203": "CZ", "208": "DK", "233": "EE",
  "246": "FI", "250": "FR", "276": "DE", "300": "GR", "348": "HU", "352": "IS", "372": "IE", "380": "IT",
  "428": "LV", "438": "LI", "440": "LT", "442": "LU", "470": "MT", "528": "NL", "578": "NO", "616": "PL",
  "620": "PT", "642": "RO", "703": "SK", "705": "SI", "724": "ES", "752": "SE", "756": "CH",
  "248": "FI", // Åland, a separate shape in Natural Earth
};

// Mainland Europe plus Iceland and Cyprus; overseas territories (French
// Guiana, the Canaries, Svalbard's far north) fall outside and are cut.
const WEST = -25, EAST = 45, SOUTH = 34, NORTH = 71.5;
const WIDTH = 1000;

let topology = JSON.parse(readFileSync(require.resolve("world-atlas/countries-50m.json"), "utf8"));
topology = presimplify(topology);
topology = simplify(topology, quantile(topology, 0.35));
const countries = feature(topology, topology.objects.countries).features;

// A point every degree, so the frame's edges follow the parallels —
// d3 draws polygon edges as great circles, and a straight-cornered
// frame's southern edge bulges north far enough to cut off Malta and
// Cyprus.
const edge = (from, to, point) => Array.from({ length: Math.abs(to - from) + 1 }, (_, i) => point(from + Math.sign(to - from) * i));
const frame = {
  type: "Polygon",
  coordinates: [[
    ...edge(SOUTH, NORTH, (lat) => [WEST, lat]),
    ...edge(WEST, EAST, (lon) => [lon, NORTH]).slice(1),
    ...edge(NORTH, SOUTH, (lat) => [EAST, lat]).slice(1),
    ...edge(EAST, WEST, (lon) => [lon, SOUTH]).slice(1),
  ]],
};
const projection = geoAzimuthalEqualArea().rotate([-10, -52]);
projection.fitWidth(WIDTH, frame);
const [[, top], [, bottom]] = geoPath(projection).bounds(frame);
const HEIGHT = Math.ceil(bottom - top);
projection.fitSize([WIDTH, HEIGHT], frame).clipExtent([[0, 0], [WIDTH, HEIGHT]]);
const path = geoPath(projection).digits(1);

const shapes = [];
// Kept if any of it lands inside the frame — the clip extent already cuts
// everything else (a bounding-box test would drop Russia, whose bounds
// wrap around the antimeridian).
for (const country of countries) {
  const d = path(country);
  if (!d || path.area(country) < 1) continue;
  const code = COVERED[country.id] ?? null;
  const [x, y] = path.centroid(country);
  shapes.push({ code, name: country.properties.name, d, labelX: Math.round(x), labelY: Math.round(y), area: Math.round(path.area(country)) });
}
shapes.sort((a, b) => Number(Boolean(a.code)) - Number(Boolean(b.code)) || a.name.localeCompare(b.name));

const missing = Object.values(COVERED).filter((code) => !shapes.some((s) => s.code === code));
if (missing.length) throw new Error(`Missing covered countries: ${missing.join(", ")}`);

const body = `// Generated by scripts/build-europe-map.mjs from Natural Earth 1:50m
// country borders (public domain) — do not edit by hand.
import type { CountryCode } from "../types/domain";

export interface MapShape {
  code: CountryCode | null; // null = outside InternEZ's coverage, drawn as context
  name: string;
  d: string;
  labelX: number;
  labelY: number;
  area: number;
}

export const MAP_WIDTH = ${WIDTH};
export const MAP_HEIGHT = ${HEIGHT};

export const MAP_SHAPES: MapShape[] = ${JSON.stringify(shapes, null, 0).replace(/\},\{/g, "},\n  {").replace(/^\[/, "[\n  ").replace(/\]$/, ",\n]")};
`;
writeFileSync(output, body);
console.log(`${shapes.length} shapes, ${HEIGHT}px tall, ${Math.round(body.length / 1024)} KB`);
