export interface Plural {
  zero?: string;
  one?: string;
  two?: string;
  few?: string;
  many?: string;
  other: string;
}

export type MessageKey = keyof typeof enMessages;

// A translation must give every key, as a plain string where English has
// one and as plural forms where English does.
export type Messages = { [K in MessageKey]: (typeof enMessages)[K] extends string ? string : Plural };

